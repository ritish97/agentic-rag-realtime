"""
src/tools/rag_tool.py

Wraps the FAISS knowledge base search as a LangChain Tool so the agent can
call it alongside web search, finance, weather, and Wikipedia tools.

KEY CONCEPT — Tool Description is Critical:
    The agent's LLM evaluates the `description` field to decide WHEN to call this
    tool. A precise description detailing what the internal knowledge base
    contains ensures proper routing between internal documentation and external APIs.
"""

from typing import List

try:
    from langchain_core.tools import Tool
except ImportError:
    from langchain.tools import Tool  # type: ignore

from langchain_community.vectorstores import FAISS

from src.knowledge_indexer import search_knowledge_base


def create_rag_tool(
    vector_store: FAISS,
    domain_description: str = "internal company documents, valuation forecasts, and policies",
) -> Tool:
    """
    Build a LangChain Tool that searches the FAISS knowledge base.

    Input/Output contract:
        - Input:  plain string query generated by the agent.
        - Output: formatted retrieval results with numbered source chunks.

    Args:
        vector_store:       Loaded FAISS index returned by knowledge_indexer.
        domain_description: Short phrase describing what is stored in the KB.

    Returns:
        A configured LangChain Tool ready for agent execution.
    """

    def _search(query: str) -> str:
        """
        Inner function called by LangChain when the agent invokes this tool.
        """
        chunks: List[str] = search_knowledge_base(query, vector_store, k=3)

        if not chunks:
            return "No relevant information found in internal knowledge base."

        lines = ["Found in internal knowledge base:"]
        for i, chunk in enumerate(chunks, start=1):
            clean = " ".join(chunk.split())
            lines.append(f"{i}. {clean}")

        return "\n".join(lines)

    description = (
        f"Search {domain_description} for relevant information. "
        "Use this for questions about internal corporate policies, valuation models, "
        "forward forecasts, AI architecture directives, or operational guidelines. "
        "Input: a search query string."
    )

    return Tool(
        name="search_knowledge_base",
        func=_search,
        description=description,
    )
